import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const home=readFileSync('src/components/news/TechnologyHome.astro','utf8');
const layout=readFileSync('src/layouts/TechnologyLayout.astro','utf8');
const css=readFileSync('src/styles/technology.css','utf8');
const article=readFileSync('src/pages/[...slug].astro','utf8');
const archive=readFileSync('src/pages/arsiv/index.astro','utf8');
let count=0;
function check(ok,label){assert.ok(ok,label);count++;}
check(home.includes("publicationEra: 'technology'"),'only current technology feed');
check(!home.includes("publicationEra: 'legacy'"),'historical feed not fetched into homepage');
check(!home.includes('<h1>Teknoloji</h1>'),'no giant duplicative technology heading');
check(home.includes('<h1>Son haberler</h1>'),'compact news-first heading');
check(home.includes('Şu anda yayımlanmış bir haber bulunmuyor.'),'no fabricated news');
check(!home.includes('Arşivden teknoloji'),'old archive never surfaced');
check(!home.includes('<img'),'editorial frontend remains text-first');
check(layout.includes('ep-wordmark'),'publication masthead retained');
check(!layout.includes('OturumDugmesi'),'reader navigation has no OAuth consent dependency');
check(!layout.includes('data-topic-link="arsiv"'),'removed historical navigation');
check(css.includes('clamp(30px, 3.1vw, 43px)'),'masthead remains restrained');
check(layout.includes('data-theme-toggle'),'accessible theme retained');
check(article.includes("publicationEra: 'technology'"),'static public routes exclude old stories');
check(archive.includes('status: 410'),'legacy archive is gone');
console.log('Equinox Haber editorial design: '+count+' checks passed');

check(!layout.includes('HABERİN KAYNAĞINA YAKIN'),'no promotional masthead slogan');
check(!layout.includes('Bağımsız teknoloji yayını'),'no redundant utility slogan');
check(!home.includes('EQUINOX HABER / GÜNDEM'),'no repeated masthead in homepage');
check(home.includes('<h2>Yayıncılar</h2>'),'clear sidebar editorial identity');
console.log('Equinox Haber editorial design: '+count+' checks passed');
